function extractAirportCode(locationString) {
  if (!locationString) return '';
  const match = locationString.match(/\(([A-Z]{3})\)/);
  if (match) return match[1];
  return locationString.slice(0, 3).toUpperCase();
}

function getFlights({ origin, destination, cabin = 'Economy' } = {}) {
  const originCode = extractAirportCode(origin) || 'AMD';
  const destCode = extractAirportCode(destination) || 'BOM';
  const originCity = origin ? origin.split('(')[0].trim() : 'Ahmedabad';
  const destinationCity = destination ? destination.split('(')[0].trim() : 'Mumbai';

  return INITIAL_MOCK_FLIGHTS.map((flight) => {
    let multiplier = 1;
    if (cabin === 'Business') multiplier = 2.4;
    else if (cabin === 'Premium Economy') multiplier = 1.5;
    else if (cabin === 'First') multiplier = 4.0;

    return {
      ...flight,
      cabin: cabin || flight.cabin,
      price: Math.round(flight.price * multiplier),
      originCode,
      destinationCode: destCode,
      originCity,
      destinationCity
    };
  });
}

