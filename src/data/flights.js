export function getMockFlights(searchCriteria) {
  const originCode = extractAirportCode(searchCriteria?.origin) || 'AMD';
  const destCode = extractAirportCode(searchCriteria?.destination) || 'BOM';

  return INITIAL_MOCK_FLIGHTS.map((flight) => ({
    ...flight,
    originCode,
    destinationCode: destCode,
    originCity: searchCriteria?.origin?.split('(')[0]?.trim() || 'Ahmedabad',
    destinationCity: searchCriteria?.destination?.split('(')[0]?.trim() || 'Mumbai',
  }));
}

export function extractAirportCode(locationString) {
  if (!locationString) return '';
  const match = locationString.match(/\(([A-Z]{3})\)/);
  if (match) return match[1];
  return locationString.slice(0, 3).toUpperCase();
}

/**
 * Returns nearby date price points for the Flexible Dates feature
 */
export function getFlexibleDates(baseDate, basePrice = 4250) {
  const d = baseDate ? new Date(baseDate) : new Date();
  const offsets = [-3, -2, -1, 0, 1, 2, 3];
  const priceVariations = [-600, -350, +450, 0, +280, -750, +890];

  return offsets.map((offset, idx) => {
    const targetDate = new Date(d);
    targetDate.setDate(d.getDate() + offset);
    const dayName = targetDate.toLocaleDateString('en-US', { weekday: 'short' });
    const monthName = targetDate.toLocaleDateString('en-US', { month: 'short' });
    const dayNum = targetDate.getDate();
    const calculatedPrice = Math.max(2699, basePrice + priceVariations[idx]);

    return {
      date: targetDate,
      dateString: `${dayName}, ${dayNum} ${monthName}`,
      shortDate: `${dayNum} ${monthName}`,
      price: calculatedPrice,
      isCheapest: calculatedPrice <= 3500 || idx === 5,
      isCurrent: offset === 0
    };
  });
}

/**
 * Generates monthly price heatmap data for Cheapest Month view
 */
export function getCheapestMonthDays(monthOffset = 0, basePrice = 3800, baseDate = null) {
  const reference = baseDate ? new Date(baseDate) : new Date();
  const year = reference.getFullYear();
  const month = reference.getMonth() + monthOffset;
  const targetMonthDate = new Date(year, month, 1);
  const daysInMonth = new Date(targetMonthDate.getFullYear(), targetMonthDate.getMonth() + 1, 0).getDate();
  const monthName = targetMonthDate.toLocaleDateString('en-US', { month: 'long', year: 'numeric' });

  const days = [];
  for (let i = 1; i <= daysInMonth; i++) {
    const dayDate = new Date(targetMonthDate.getFullYear(), targetMonthDate.getMonth(), i);
    // Deterministic price fluctuation
    const mod = (i * 37) % 15;
    let price = basePrice + (mod - 7) * 220;
    if (price < 2600) price = 2690;

    days.push({
      dayNumber: i,
      dayName: dayDate.toLocaleDateString('en-US', { weekday: 'narrow' }),
      date: dayDate,
      price,
      isLow: price <= 3200,
      isMedium: price > 3200 && price <= 4500,
      isHigh: price > 4500
    });
  }

  return { monthName, days, targetMonthDate };
}
